#!/usr/bin/env python3
"""Generate an avatar's boot image and name as C data for the elena-stackchan board.

The boot screen appears before assets load, so its art is compiled into the app.
The name is an image rather than a font: it is the only text in that typeface.

Run this by hand when an avatar's art or name changes, and commit the output. The
build never runs it, because it needs Pillow:

    ../.venv-firmware/bin/python scripts/avatar_boot_assets.py \
        --avatar-dir main/boards/elena-stackchan/avatars/elena \
        --source ../assets/elena-readme.png \
        --font main/boards/elena-stackchan/avatars/fonts/CherryBombOne-Regular.ttf \
        --display-name Elena-Chan --name-color '#8A5A1E'
"""

import argparse
from pathlib import Path

MAX_IMAGE_SIZE = (132, 123)
NAME_FONT_SIZE = 28
BYTES_PER_LINE = 16


def encode_rgb565a8(rgba: bytes, width: int, height: int) -> bytes:
    """Return LVGL's RGB565A8: every pixel as little-endian RGB565, then every alpha."""
    if len(rgba) != width * height * 4:
        raise ValueError(f"expected {width * height * 4} RGBA bytes, got {len(rgba)}")
    colors = bytearray()
    alphas = bytearray()
    for offset in range(0, len(rgba), 4):
        red, green, blue, alpha = rgba[offset:offset + 4]
        value = ((red & 0xF8) << 8) | ((green & 0xFC) << 3) | (blue >> 3)
        colors += value.to_bytes(2, "little")
        alphas.append(alpha)
    return bytes(colors + alphas)


def render_image_c(symbol: str, data: bytes, width: int, height: int) -> str:
    """Return a C source file that declares one RGB565A8 LVGL image."""
    lines = []
    for offset in range(0, len(data), BYTES_PER_LINE):
        chunk = data[offset:offset + BYTES_PER_LINE]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    body = "\n".join(lines)
    return f"""// Generated by scripts/avatar_boot_assets.py. Do not edit.
#include "lvgl.h"

static const uint8_t {symbol}_data[] = {{
{body}
}};

const lv_image_dsc_t {symbol} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565A8,
        .w = {width},
        .h = {height},
        .stride = {width * 2},
    }},
    .data_size = {len(data)},
    .data = {symbol}_data,
}};
"""


def write_image(path: Path, symbol: str, image) -> None:
    rgba = image.convert("RGBA")
    data = encode_rgb565a8(rgba.tobytes(), rgba.width, rgba.height)
    path.write_text(render_image_c(symbol, data, rgba.width, rgba.height), encoding="utf-8")
    print(f"{path}: {rgba.width}x{rgba.height}, {len(data)} bytes")


def generate(avatar_dir: Path, source: Path, font: Path, display_name: str, name_color: str) -> None:
    from PIL import Image, ImageColor, ImageDraw, ImageFont

    # thumbnail only shrinks, and it keeps the proportions.
    image = Image.open(source).convert("RGBA")
    image.thumbnail(MAX_IMAGE_SIZE, Image.LANCZOS)
    image.save(avatar_dir / "boot.png")
    write_image(avatar_dir / "boot_image.c", "avatar_boot_image", image)

    # Draw coverage on its own, so edges fade in alpha and keep the name's color.
    typeface = ImageFont.truetype(str(font), NAME_FONT_SIZE)
    left, top, right, bottom = typeface.getbbox(display_name)
    mask = Image.new("L", (right - left, bottom - top), 0)
    ImageDraw.Draw(mask).text((-left, -top), display_name, font=typeface, fill=255)
    name = Image.new("RGBA", mask.size, ImageColor.getrgb(name_color) + (255,))
    name.putalpha(mask)
    write_image(avatar_dir / "boot_name.c", "avatar_boot_name", name)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--avatar-dir", type=Path, required=True)
    parser.add_argument("--source", type=Path, required=True, help="The boot image's source")
    parser.add_argument("--font", type=Path, required=True)
    parser.add_argument("--display-name", required=True)
    parser.add_argument("--name-color", required=True, help="#RRGGBB")
    args = parser.parse_args()
    generate(args.avatar_dir, args.source, args.font, args.display_name, args.name_color)


if __name__ == "__main__":
    main()
